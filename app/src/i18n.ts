const DICTS: Record<Lang, Dict> = { he, en };

let current: Lang = 'he';

export function detectLang(): Lang {
  const list = (navigator.languages?.length ? navigator.languages : [navigator.language]) || [];
  for (const l of list) {
    const c = String(l).toLowerCase();
    if (c.startsWith('he') || c.startsWith('iw')) return 'he';
    if (c.startsWith('en')) return 'en';
  }
  return list.length ? 'en' : 'he';
}

export function setLang(l: Lang) {
  current = l;
  document.documentElement.lang = l;
  document.documentElement.dir = l === 'he' ? 'rtl' : 'ltr';
}

export const lang = () => current;
export const rtl = () => current === 'he';

export function t(k: Key, vars?: Record<string, string | number>): string {
  let s = DICTS[current][k] ?? DICTS.he[k] ?? k;
  if (vars) for (const [n, v] of Object.entries(vars)) s = s.split('{' + n + '}').join(String(v));
  return s;
}

export function tl(l: Lang, k: Key, vars?: Record<string, string | number>): string {
  let s = DICTS[l][k] ?? k;
  if (vars) for (const [n, v] of Object.entries(vars)) s = s.split('{' + n + '}').join(String(v));
  return s;
}

export const allKeys = () => Object.keys(he) as Key[];
export const dict = (l: Lang) => DICTS[l];
